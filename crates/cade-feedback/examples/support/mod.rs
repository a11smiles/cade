//! Deterministic generation shared by the stdout example and read-only staleness tests.

use cade_feedback::{Answer, Environment, Feedback, FeedbackKind, IssueDraft};
use std::collections::BTreeMap;
use std::error::Error;
use std::path::Path;
use ts_rs::{Config, TS};

#[path = "../../../../app/src-tauri/src/command_error.rs"]
pub(crate) mod command_error;

use command_error::CommandError;

// Consume the app's declaration tokens, not a parsed source string or a second
// command table. Injected state and native bodies need no webview dependencies.
macro_rules! commands {
    ($(
        $(#[$meta:meta])*
        $mode:ident fn $name:ident(
            [$($injected:ident: $injected_ty:ty),*] $(, $arg:ident: $arg_ty:ty)*
        ) -> Result<$result:ty, $error:ty> $body:block
    )*) => {
        fn command_declaration(config: &Config) -> String {
            let mut output = String::from("type Commands = {\n");
            $(
                output.push_str(concat!(stringify!($name), ": { args: "));
                output.push_str(&commands!(@args config; $($arg: $arg_ty),*));
                output.push_str("; result: ");
                output.push_str(&<$result as TS>::name(config));
                output.push_str("; error: ");
                output.push_str(&<$error as TS>::name(config));
                output.push_str(" };\n");
            )*
            output.push_str("};");
            output
        }
    };
    (@args $config:ident;) => {
        String::from("undefined")
    };
    (@args $config:ident; $($arg:ident: $arg_ty:ty),+) => {{
        let mut args = String::from("{ ");
        $(
            args.push_str(concat!(stringify!($arg), ": "));
            args.push_str(&<$arg_ty as TS>::name($config));
            args.push_str("; ");
        )+
        args.push('}');
        args
    }};
}

include!("../../../../app/src-tauri/src/commands.rs");

pub(crate) fn bindings() -> String {
    let config = Config::new();
    let declarations = [
        FeedbackKind::decl(&config),
        Answer::decl(&config),
        Environment::decl(&config),
        Feedback::decl(&config),
        IssueDraft::decl(&config),
        command_error::CommandError::decl(&config),
        serde_json::Value::decl(&config),
        command_declaration(&config),
    ];
    let mut output = String::from("// Generated by cade-feedback. Do not edit; run generate_feedback -- bindings.\n\n");
    for declaration in declarations {
        output.push_str("export ");
        for line in declaration.lines() {
            output.push_str(line.trim_end());
            output.push('\n');
        }
    }
    output
}

pub(crate) fn forms() -> Result<String, Box<dyn Error>> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../.github/ISSUE_TEMPLATE");
    let mut forms = BTreeMap::new();
    for kind in [FeedbackKind::Bug, FeedbackKind::FeatureRequest, FeedbackKind::Comment] {
        let yaml = std::fs::read_to_string(root.join(kind.template()))?;
        let mut form: serde_json::Value = serde_yaml_ng::from_str(&yaml)?;
        form.sort_all_objects();
        let key = serde_json::to_value(kind)?;
        forms.insert(key.as_str().ok_or("feedback kind must serialize as a string")?.to_owned(), form);
    }
    Ok(format!(
        "// Generated by cade-feedback from .github/ISSUE_TEMPLATE. Do not edit; run generate_feedback -- forms.\n\
         import type {{ FeedbackKind }} from '../ipc/bindings';\n\n\
         export const FORMS = {} as const satisfies Record<FeedbackKind, unknown>;\n",
        serde_json::to_string_pretty(&forms)?
    ))
}
